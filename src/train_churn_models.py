# 4) Lightweight Artifact for AWS – TODO (Bonus)
def build_lightweight_artifact(
    df,
    preprocessor,
    numeric_features,
    categorical_features,
    sgd_model,
):
    """
    Build a JSON-serializable artifact containing the fitted preprocessing
    parameters and the fitted SGDClassifier coefficients.

    Note: the coefficients must be paired with the same fitted preprocessor
    used when training the SGD model. Therefore, this function extracts the
    preprocessor from the trained SGD pipeline instead of refitting a new one.
    """
    fitted_preprocessor = sgd_model.named_steps["preprocessor"]

    num_pipe = fitted_preprocessor.named_transformers_["num"]
    num_imputer = num_pipe.named_steps["imputer"]
    scaler = num_pipe.named_steps["scaler"]

    cat_pipe = fitted_preprocessor.named_transformers_["cat"]
    cat_imputer = cat_pipe.named_steps["imputer"]
    ohe = cat_pipe.named_steps["onehot"]

    clf = sgd_model.named_steps["clf"]

    numeric_names = list(fitted_preprocessor.transformers_[0][2])
    categorical_names = list(fitted_preprocessor.transformers_[1][2])
    onehot_feature_names = ohe.get_feature_names_out(categorical_names).tolist()
    final_feature_names = numeric_names + onehot_feature_names

    artifact = {
        "model_type": "SGDClassifier_log_loss",
        "target": "Churn",
        "positive_class": 1,
        "threshold": 0.5,
        "numeric_features": numeric_names,
        "numeric_imputer_medians": num_imputer.statistics_.tolist(),
        "numeric_means": scaler.mean_.tolist(),
        "numeric_scales": scaler.scale_.tolist(),
        "categorical_features": categorical_names,
        "categorical_imputer_values": cat_imputer.statistics_.tolist(),
        "categories": [category.tolist() for category in ohe.categories_],
        "onehot_feature_names": onehot_feature_names,
        "final_feature_names": final_feature_names,
        "coef": clf.coef_.tolist(),
        "intercept": clf.intercept_.tolist(),
    }

    return artifact


