# Scikit-Learn Models – TODO
def train_sklearn_models(preprocessor, X, y):
    """
    Train several Scikit-Learn models using the same preprocessing structure
    and evaluate them with validation AUC and accuracy.

    Returns:
      - results: list of (name, trained_pipeline, auc, accuracy), sorted by AUC
      - splits: (X_train, X_val, y_train, y_val)
      - sgd_model: trained SGDClassifier pipeline for possible deployment
      - sgd_auc: validation AUC of the SGDClassifier
    """
    X_train, X_val, y_train, y_val = train_test_split(
        X,
        y,
        test_size=0.20,
        random_state=42,
        stratify=y,
    )

    candidate_models = {
        "Logistic Regression": LogisticRegression(
            max_iter=1000,
            class_weight="balanced",
            random_state=42,
        ),
        "Random Forest": RandomForestClassifier(
            n_estimators=300,
            min_samples_leaf=2,
            class_weight="balanced",
            random_state=42,
            n_jobs=-1,
        ),
        "Gradient Boosting": GradientBoostingClassifier(
            random_state=42,
        ),
        "SGD Classifier": SGDClassifier(
            loss="log_loss",
            penalty="l2",
            alpha=1e-4,
            max_iter=2000,
            tol=1e-3,
            class_weight="balanced",
            random_state=42,
        ),
    }

    results = []
    sgd_model = None
    sgd_auc = None

    for model_name, clf in candidate_models.items():
        pipe = Pipeline(
            steps=[
                ("preprocessor", clone(preprocessor)),
                ("clf", clf),
            ]
        )

        pipe.fit(X_train, y_train)

        if hasattr(pipe.named_steps["clf"], "predict_proba"):
            y_val_proba = pipe.predict_proba(X_val)[:, 1]
        else:
            y_val_score = pipe.decision_function(X_val)
            y_val_proba = 1 / (1 + np.exp(-y_val_score))

        y_val_pred = (y_val_proba >= 0.5).astype(int)
        auc = roc_auc_score(y_val, y_val_proba)
        acc = accuracy_score(y_val, y_val_pred)

        results.append((model_name, pipe, auc, acc))

        print(f"{model_name:20s}  AUC={auc:.4f}  ACC={acc:.4f}")

        if model_name == "SGD Classifier":
            sgd_model = pipe
            sgd_auc = auc

    results.sort(key=lambda item: item[2], reverse=True)

    return results, (X_train, X_val, y_train, y_val), sgd_model, sgd_auc


