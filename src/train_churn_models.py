# Keras Model
def build_keras_model(input_dim: int):
    """
    Build and compile a compact Keras MLP for binary churn classification.

    The network is intentionally small because the Telco dataset is tabular
    and not extremely large. Dropout helps reduce overfitting, while the
    sigmoid output gives a churn probability.
    """
    model = keras.Sequential(
        [
            layers.Input(shape=(input_dim,)),
            layers.Dense(64, activation="relu"),
            layers.Dropout(0.20),
            layers.Dense(32, activation="relu"),
            layers.Dropout(0.20),
            layers.Dense(16, activation="relu"),
            layers.Dense(1, activation="sigmoid"),
        ]
    )

    model.compile(
        optimizer=keras.optimizers.Adam(learning_rate=1e-3),
        loss="binary_crossentropy",
        metrics=[keras.metrics.AUC(name="auc"), "accuracy"],
    )

    return model


